/**
 * 이메일 정규화 — **이 규칙의 단일 출처**다. 순수 함수라 Nest·DB 를 모른다.
 *
 * 저장·조회·검증이 **반드시 같은 규칙**을 써야 한다:
 *  - 대소문자를 안 맞추면 `Kim@x.com` 으로 가입한 사람이 `kim@x.com` 으로 로그인할 때 못 찾고,
 *    더 나쁘게는 `email @unique` 를 통과해 **같은 사람의 계정이 두 개** 생긴다(재고가 한쪽에만 쌓인다).
 *  - 공백을 안 떼면 `@IsEmail()` 이 원본을 보고 형식 오류로 거절한다(실측으로 확인).
 *
 * 그래서 DTO 의 `@Transform` 과 서비스가 **둘 다 이 함수를 부른다.** DTO 는 검증 입력을 다듬으려고,
 * 서비스는 DTO 를 안 거치는 경로(소셜 로그인이 provider 에게서 받은 이메일)까지 덮으려고.
 * 같은 함수라 두 번 불려도 결과가 같다(멱등).
 */
export const normalizeEmail = (email: string): string => email.trim().toLowerCase();
