import { z } from 'zod';

export const EXTRACTION_SCHEMA_NAME = 'memory_extraction';

/**
 * 추출 LLM 의 구조화 출력 스키마 (zod → SDK 가 JSON 스키마를 자동 생성).
 * category 는 enum 으로 제약해 잘못된 값을 원천 차단한다.
 * importance 범위(1~3)는 프롬프트 지시 + 저장 시 코드 클램프로 통제한다.
 */
export const ExtractionSchema = z.object({
  memories: z.array(
    z.object({
      category: z.enum(['PREFERENCE', 'PROFILE', 'OWNERSHIP', 'ETC']),
      content: z.string(),
      importance: z.number().int(),
    }),
  ),
});

/** 추출 결과 타입 — zod 스키마에서 추론 (수동 인터페이스 불필요) */
export type ExtractionResult = z.infer<typeof ExtractionSchema>;

/** 추출 instruction 조립 — 기존 메모리를 함께 줘서 의미상 중복을 피하게 한다. */
export function buildExtractionInstruction(existing: string[]): string {
  const known = existing.length ? existing.map((c) => `- ${c}`).join('\n') : '(없음)';
  return `너는 사용자의 '요리·식생활'을 돕기 위해 사용자에 대한 장기 기억을 관리하는 추출기다.
아래 대화에서, 앞으로의 여러 끼니에 두루 쓰일 '오래 지속되는 사실'만 골라 구조화해 반환하라.

[가장 중요한 경계 — 재료 재고는 절대 뽑지 마라]
지금 뭘 가지고 있는지는 **냉장고 시스템이 따로 관리한다.** 여기에 또 저장하면 두 기록이 어긋난다.
- "계란 있음", "우유 샀음", "대파 다 씀", "삼겹살 600g" → 전부 버림. 예외 없다.
- 사람의 성향이면 저장: "계란 알레르기가 있음"(사람) vs "계란 있음"(재고) 을 반드시 구분하라.

[그 다음 기준 — 사람에 묶이면 저장, 이번 한 끼에 묶이면 버림]
- 재료·요리 이름을 떼도 말이 되는 정보(사람의 식성·특성)만 뽑아라 → 저장
- 그때그때의 요구는 장기 기억이 아니다 → 버림
  예: "오늘은 간단한 거 먹고 싶어" / "이번엔 안 매운 걸로" → 버림.
  단, 반복되거나 명시적 단서가 있으면("난 원래 매운 걸 잘 못 먹어") 사람 특성("매운 음식을 잘 못 먹음")으로 승격해 저장.
  한 번의 요청으로 일반 성향을 단정하지 마라.

[뽑을 것] 여러 끼니에 두루 적용되는, 사람에 묶이는 지속 정보
[뽑지 말 것]
- **냉장고에 뭐가 있는지·뭘 샀는지·뭘 다 썼는지 (재고 — 위 참고)**
- 이번 한 끼에만 해당하는 요구("오늘은 국물 있는 거")
- 일회성 이벤트/약속/일정("내일 시험", "금요일 약속")
- 순간의 기분/감정("오늘 피곤함", "배고픔")
- 컴패니언(너) 자신에 대한 정보, 일반 상식·레시피 지식

[이미 알고 있는 사실] (아래와 의미가 겹치면 다시 만들지 마라):
${known}

[카테고리] 각 사실에 가장 잘 맞는 하나만 고른다:
- PREFERENCE: 식성·입맛("매운 음식을 좋아함", "오이를 싫어함", "채식 위주", "아침을 잘 안 먹음")
- PROFILE: 알레르기·체질·상황·요리 실력("갑각류 알레르기가 있음", "자취 중", "요리 초보", "1인분만 해먹음")
- OWNERSHIP: 조리도구·주방 환경("에어프라이어 있음", "인덕션 씀", "냄비가 하나뿐임")
  ※ **식재료가 아니라 도구·설비만** 담는다. 재료는 냉장고 담당이다.
- ETC: 위 어디에도 안 맞는 지속 사실

[content 형식] 짧고 자연스러운 한 구절("자취 중"). 사실 1개 = 항목 1개.
[importance] 1~3 정수 (1=사소, 2=보통, 3=핵심).
  ※ 알레르기·못 먹는 음식은 **안전 문제**라 반드시 3으로 하고, 먹으면 안 된다는 걸 content 에 분명히 적어라.
새로 기억할 게 없으면 빈 배열을 반환하라.`;
}
